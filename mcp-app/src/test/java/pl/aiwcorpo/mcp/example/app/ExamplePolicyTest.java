package pl.aiwcorpo.mcp.example.app;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;
import pl.aiwcorpo.mcp.cedar.entities.Caller;
import pl.aiwcorpo.mcp.cedar.entities.ResolvedResource;
import pl.aiwcorpo.mcp.cedar.entities.Scopes;
import pl.aiwcorpo.mcp.platform.test.PolicyDecisions;

/**
 * The decisions of the server's own policies ({@code src/main/resources/mcp/policies/}) as a plain JUnit test: no Spring
 * context, no gateway, no backend. The resources are built as the resolver would build them (declared attributes,
 * parent, scopes); the scope mapping is what an administrator would set in the gateway. The rules for restricted data
 * and for the service account are generated by the platform, and are tested here as part of the decision.
 */
class ExamplePolicyTest {

    private static final String READ = "mcp-example-read";
    private static final String WRITE = "mcp-example-write";
    private static final String GRANTS_ABC = "mcp-example-proj-ABC";
    private static final String GRANTS_DEF = "mcp-example-proj-DEF";

    private final PolicyDecisions policies = PolicyDecisions.fromResources()
            .scopeMapping(Map.of(GRANTS_ABC, List.of("Example::Project/ABC"), GRANTS_DEF, List.of("Example::Project/DEF")));

    private static ResolvedResource record(String id, String project, String category) {
        List<String> scopes = List.of(Scopes.id("Example::Project", project));
        ResolvedResource container = ResolvedResource.of("Example::Project", project, Map.of("key", project, "category", category))
                .withScopes(scopes);
        return ResolvedResource.of("Example::Record", id, Map.of("key", id)).withParent(container).withScopes(scopes);
    }

    private static final ResolvedResource OPEN = record("ABC-1", "ABC", "");
    private static final ResolvedResource RESTRICTED = record("HR-5", "HR", "Restricted");

    @Test
    void theReadGroupReadsEveryRecordTheSystemShowsItAndNobodyElseDoes() {
        policies.assertAllowed(PolicyDecisions.caller(READ), "read", OPEN);
        policies.assertAllowed(PolicyDecisions.caller(READ), "read", record("DEF-7", "DEF", ""));
        policies.assertDenied(PolicyDecisions.caller(WRITE, GRANTS_ABC), "read", OPEN);
        policies.assertDenied(PolicyDecisions.caller(), "read", OPEN);
    }

    @Test
    void aChangeNeedsTheWriteGroupAndAScopeThatCoversTheRecord() {
        policies.assertAllowed(PolicyDecisions.caller(WRITE, GRANTS_ABC), "update", OPEN);
        policies.assertDenied(PolicyDecisions.caller(WRITE), "update", OPEN);
        policies.assertDenied(PolicyDecisions.caller(WRITE, GRANTS_DEF), "update", OPEN);
        policies.assertDenied(PolicyDecisions.caller(READ, GRANTS_ABC), "update", OPEN);
    }

    @Test
    void aScopeGrantedOnOneProjectNeverReachesAnother() {
        Caller writer = PolicyDecisions.caller(WRITE, GRANTS_ABC);

        policies.assertAllowed(writer, "update", record("ABC-2", "ABC", ""));
        policies.assertDenied(writer, "update", record("DEF-7", "DEF", ""));
        policies.assertDenied(writer, "update", record("ABC1-1", "ABC1", ""));
    }

    @Test
    void restrictedDataIsRefusedForEveryActionWhateverTheGroupsAndScopes() {
        Caller everything = PolicyDecisions.caller(READ, WRITE, GRANTS_ABC);
        policies.scopeMapping(Map.of(GRANTS_ABC, List.of("Example::Project/ABC", "Example::Project/HR")));

        policies.assertDenied(everything, "read", RESTRICTED);
        policies.assertDenied(everything, "update", RESTRICTED);
    }

    @Test
    void theClassificationIsNormalizedBeforeItIsCompared() {
        Caller reader = PolicyDecisions.caller(READ);

        policies.assertDenied(reader, "read", record("HR-6", "HR", "RESTRICTED"));
        policies.assertDenied(reader, "read", record("HR-7", "HR", "  restricted "));
        policies.assertAllowed(reader, "read", record("HR-8", "HR", "restricted-ish"));
    }

    @Test
    void theServiceAccountReadsOnlyInsideTheScopesOfTheUser() {
        PolicyDecisions asServiceAccount = policies.credentialType("service-account");

        asServiceAccount.assertDenied(PolicyDecisions.caller(READ), "read", OPEN);
        asServiceAccount.assertAllowed(PolicyDecisions.caller(READ, GRANTS_ABC), "read", OPEN);
        asServiceAccount.assertDenied(PolicyDecisions.caller(READ, GRANTS_DEF), "read", OPEN);
    }

    @Test
    void aCallerOfAClientTheGatewayDoesNotAllowIsDenied() {
        policies.allowedClients("claude-ai");

        policies.assertDenied(PolicyDecisions.caller(READ), "read", OPEN);
    }

    @Test
    void anEmergencyOverrideOfTheAdministratorClosesChangesAndLeavesReadsAlone() {
        policies.override("override-freeze", "forbid (principal, action == Example::Action::\"update\", resource);");

        policies.assertDenied(PolicyDecisions.caller(WRITE, GRANTS_ABC), "update", OPEN);
        policies.assertAllowed(PolicyDecisions.caller(READ), "read", OPEN);
    }

    @Test
    void aResourceThatDoesNotMatchItsDeclarationIsRefusedAsInTheServer() {
        Caller reader = PolicyDecisions.caller(READ);
        ResolvedResource unclassified = ResolvedResource.of("Example::Project", "NOC", Map.of("key", "NOC"));

        assertThatThrownBy(() -> policies.decide(reader, "read",
                ResolvedResource.of("Example::Record", "NOC-1", Map.of("key", "NOC-1")).withParent(unclassified)
                        .withScopes(List.of("Example::Project/NOC"))))
                .as("a project without its required classification is not built")
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> policies.decide(reader, "read", record("abc-1", "ABC", "")))
                .as("an id outside the idPattern")
                .isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    void theDeclarationsMakeTheProjectGrantableAndKeepTheRecordIdsToTheirPattern() {
        assertThat(policies.serverPolicies().resourceTypes().isValidId("Example::Record", "ABC-1")).isTrue();
        assertThat(policies.serverPolicies().resourceTypes().isValidId("Example::Record", "ABC-0")).isFalse();
        assertThat(policies.serverPolicies().resourceTypes().isValidId("Example::Project", "ABC")).isTrue();
    }
}
